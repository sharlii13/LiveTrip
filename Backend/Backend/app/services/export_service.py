# app/services/export_service.py
import json
import io
import base64
from datetime import datetime
from typing import Dict, Optional, List
from fastapi import HTTPException
from fastapi.responses import StreamingResponse, HTMLResponse
import logging

logger = logging.getLogger(__name__)

class ExportService:
    def __init__(self):
        self.supported_formats = ["pdf", "json", "txt"]
        self.shared_itineraries = {}  # In-memory storage for hackathon
        
    async def generate_itinerary_pdf(self, trip_data: Dict) -> bytes:
        """Generate PDF of itinerary (simple text-based for hackathon)"""
        try:
            # Generate text content
            text_content = self._generate_text_itinerary(trip_data)
            return text_content.encode('utf-8')
            
        except Exception as e:
            logger.error(f"PDF generation failed: {e}")
            raise HTTPException(status_code=500, detail=f"PDF generation failed: {str(e)}")
    
    def _generate_text_itinerary(self, trip_data: Dict) -> str:
        """Generate plain text itinerary"""
        text_content = f"""
✈️ TRAVEL ITINERARY
==================

Destination: {trip_data.get('destination', 'Unknown')}
Dates: {trip_data.get('start_date', 'N/A')} to {trip_data.get('end_date', 'N/A')}
Budget: ${trip_data.get('budget', 'N/A')}
Mood: {trip_data.get('mood', 'N/A')}
Duration: {self._calculate_duration(trip_data.get('start_date'), trip_data.get('end_date'))} days
Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}

🍽️ FOOD PREFERENCES:
"""
        
        # Add food preferences
        if trip_data.get('food_preferences'):
            for food in trip_data['food_preferences']:
                text_content += f"• {food}\n"
        else:
            text_content += "• Mixed cuisine\n• Local specialties\n"
        
        # Add eco info
        if trip_data.get('eco_mode_enabled'):
            text_content += f"""
🌱 ECO MODE: ENABLED
Eco Score: {trip_data.get('eco_score', 85)}/100
Carbon Footprint Saved: {trip_data.get('carbon_footprint_saved', 12.5)} kg CO₂
Transport Preference: {trip_data.get('transport_preference', 'Eco-friendly')}
"""
        
        text_content += "\n📅 DAILY ITINERARY:\n===============\n"
        
        if trip_data.get('itineraries'):
            for day, itinerary in enumerate(trip_data['itineraries'], 1):
                text_content += f"\nDay {day}:\n"
                text_content += "-" * 10 + "\n"
                
                activities = itinerary.get('activities', [])
                if isinstance(activities, str):
                    try:
                        activities = json.loads(activities)
                    except:
                        activities = [activities]
                
                for activity in activities:
                    if isinstance(activity, dict):
                        activity_text = f"• {activity.get('name', 'Activity')}"
                        if activity.get('time'):
                            activity_text += f" ({activity.get('time')})"
                    else:
                        activity_text = f"• {activity}"
                    text_content += activity_text + "\n"
        
        # Add personal message
        if trip_data.get('message'):
            text_content += f"\n💬 MESSAGE FROM TRAVELER:\n{trip_data['message']}\n"
        
        text_content += f"\n\nGenerated by TravelBuddy - Smart Travel Planning\nShared at: {datetime.now().strftime('%Y-%m-%d %H:%M')}\n"
        return text_content
    
    async def generate_json_export(self, trip_data: Dict) -> Dict:
        """Generate JSON export"""
        export_data = {
            "export_info": {
                "format": "json",
                "generated_at": datetime.now().isoformat(),
                "version": "1.0"
            },
            "trip_data": trip_data,
            "metadata": {
                "app": "TravelBuddy",
                "export_type": "complete_itinerary"
            }
        }
        return export_data
    
    async def generate_enhanced_shareable_link(self, trip_data: Dict, user_id: int, share_options: Dict) -> Dict:
        """Generate enhanced shareable link with all trip details"""
        try:
            trip_id = trip_data.get('id', 'temp')
            share_id = f"share_{user_id}_{trip_id}_{int(datetime.now().timestamp())}"
            
            # ✅ LOCAL DEPLOYMENT - Perfect for hackathon
            base_url = "http://localhost:8000"
            share_url = f"{base_url}/api/export/shared/{share_id}"
            
            # Process food preferences
            food_preferences = []
            if trip_data.get('preferences'):
                try:
                    prefs = json.loads(trip_data['preferences']) if isinstance(trip_data['preferences'], str) else trip_data.get('preferences', {})
                    food_preferences = prefs.get('food', ['Mixed cuisine', 'Local specialties'])
                except:
                    food_preferences = ['Mixed cuisine', 'Local specialties']
            else:
                food_preferences = ['Mixed cuisine', 'Local specialties']
            
            # Calculate eco info
            eco_mode_enabled = trip_data.get('eco_mode_enabled', False)
            eco_info = {
                "eco_mode_enabled": eco_mode_enabled,
                "transport_preference": trip_data.get('transport_preference', 'mixed'),
                "eco_score": 85 if eco_mode_enabled else 60,
                "carbon_footprint_saved": 12.5 if eco_mode_enabled else 0.0
            }
            
            # Enhanced shareable data
            enhanced_trip_data = {
                "share_id": share_id,
                "destination": trip_data.get('destination', 'Unknown'),
                "start_date": trip_data.get('start_date', ''),
                "end_date": trip_data.get('end_date', ''),
                "duration_days": self._calculate_duration(trip_data.get('start_date'), trip_data.get('end_date')),
                "message": share_options.get('message', 'Check out my amazing travel itinerary!'),
                
                # Food preferences
                "food_preferences": food_preferences if share_options.get('include_food_preferences', True) else [],
                
                # Eco information  
                "eco_mode_enabled": eco_info["eco_mode_enabled"] if share_options.get('include_eco_info', True) else None,
                "eco_score": eco_info["eco_score"] if share_options.get('include_eco_info', True) else None,
                "carbon_footprint_saved": eco_info["carbon_footprint_saved"] if share_options.get('include_eco_info', True) else None,
                "transport_preference": eco_info["transport_preference"] if share_options.get('include_eco_info', True) else None,
                
                # Optional personal info
                "budget_range": self._get_budget_range(trip_data.get('budget')) if share_options.get('include_personal_info', False) else None,
                
                # Trip characteristics
                "mood": trip_data.get('mood', 'adventurous'),
                "activities_count": len(trip_data.get('itineraries', [])),
                
                # Sharing metadata
                "shared_by": f"TravelBuddy User {user_id}",
                "created_at": datetime.now().isoformat(),
                "expires_at": (datetime.now().timestamp() + 7*24*3600),
                
                # Full itinerary data
                "itineraries": trip_data.get('itineraries', [])
            }
            
            # Store in memory for local demo
            self.shared_itineraries[share_id] = enhanced_trip_data
            
            return {
                "share_id": share_id,
                "share_url": share_url,
                "preview_url": f"{base_url}/api/export/preview/{share_id}",
                "qr_code_data": share_url,
                "expires_in_days": 7,
                "created_at": enhanced_trip_data["created_at"],
                "includes": {
                    "destination": True,
                    "dates": True,
                    "food_preferences": share_options.get('include_food_preferences', True),
                    "eco_info": share_options.get('include_eco_info', True),
                    "budget_info": share_options.get('include_personal_info', False),
                    "message": bool(share_options.get('message'))
                }
            }
            
        except Exception as e:
            logger.error(f"Enhanced share link generation failed: {e}")
            raise HTTPException(status_code=500, detail=str(e))

    def _calculate_duration(self, start_date: str, end_date: str) -> int:
        """Calculate trip duration in days"""
        try:
            if start_date and end_date:
                start = datetime.fromisoformat(start_date.replace('Z', '+00:00'))
                end = datetime.fromisoformat(end_date.replace('Z', '+00:00'))
                return (end - start).days + 1
        except:
            pass
        return 1

    def _get_budget_range(self, budget: float) -> str:
        """Convert budget to friendly range"""
        if not budget:
            return None
        
        if budget < 500:
            return "Budget-friendly (Under $500)"
        elif budget < 1500:
            return "Mid-range ($500-$1500)"
        elif budget < 3000:
            return "Premium ($1500-$3000)"
        else:
            return "Luxury ($3000+)"

# Global export service
export_service = ExportService()
