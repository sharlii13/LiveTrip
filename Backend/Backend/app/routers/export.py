# ✅ Simple Export Service Implementation
class ExportService:
    def __init__(self):
        self.shared_itineraries = {}  # In-memory storage for shared links
    
    def _generate_text_itinerary(self, trip_data: Dict) -> str:
        """Generate formatted text itinerary"""
        
        text_content = f"""
🌍 TRAVEL ITINERARY - {trip_data['destination'].upper()}
{'='*60}

📍 DESTINATION: {trip_data['destination']}
📅 DATES: {trip_data.get('start_date', 'TBD')} to {trip_data.get('end_date', 'TBD')}
💰 BUDGET: ${trip_data.get('budget', 'Not specified')}
🎭 MOOD: {trip_data.get('mood', 'Adventure').title()}
🚗 TRANSPORT: {trip_data.get('transport_preference', 'Mixed')}

"""

        # Add eco information
        if trip_data.get('eco_mode_enabled'):
            text_content += f"""
🌱 ECO-FRIENDLY TRAVEL MODE ENABLED
   • Sustainable transport options prioritized
   • Local and eco-friendly accommodations
   • Reduced carbon footprint focus

"""

        # Add food preferences
        food_prefs = trip_data.get('food_preferences', [])
        if food_prefs:
            text_content += f"""
🍽️ FOOD PREFERENCES:
"""
            for food in food_prefs:
                text_content += f"   • {food}\n"
            text_content += "\n"

        # Add daily itinerary
        text_content += f"""
📋 DAILY ITINERARY
{'='*60}

"""
        
        itineraries = trip_data.get('itineraries', [])
        for i, day_data in enumerate(itineraries, 1):
            text_content += f"""
📅 DAY {i}
{'-'*20}
"""
            activities = day_data.get('activities', [])
            if isinstance(activities, str):
                try:
                    activities = json.loads(activities)
                except:
                    activities = [activities]
            
            for activity in activities:
                if isinstance(activity, dict):
                    time_str = f" ({activity.get('time', '')})" if activity.get('time') else ""
                    text_content += f"🎯 {activity.get('name', 'Activity')}{time_str}\n"
                else:
                    text_content += f"🎯 {activity}\n"
            
            text_content += "\n"
        
        text_content += f"""
{'='*60}
✨ Generated by Live Trip - Smart Travel Planning
📱 Created: {datetime.now().strftime('%Y-%m-%d %H:%M')}
🔗 Share your adventures with friends!
{'='*60}
"""
        
        return text_content
    
    async def generate_json_export(self, trip_data: Dict) -> Dict:
        """Generate JSON export with metadata"""
        
        export_data = {
            "export_info": {
                "generated_at": datetime.now().isoformat(),
                "version": "1.0.0",
                "generator": "Live Trip API",
                "format": "json"
            },
            "trip_data": trip_data,
            "statistics": {
                "total_days": len(trip_data.get('itineraries', [])),
                "total_activities": sum(
                    len(day.get('activities', [])) for day in trip_data.get('itineraries', [])
                ),
                "has_eco_mode": trip_data.get('eco_mode_enabled', False),
                "has_food_preferences": bool(trip_data.get('food_preferences', []))
            }
        }
        
        return export_data
    
    async def generate_enhanced_shareable_link(self, trip_data: Dict, user_id: int, share_options: Dict) -> Dict:
        """Generate enhanced shareable link"""
        
        share_id = str(uuid.uuid4())[:12]  # Short unique ID
        
        # Calculate duration
        start_date = trip_data.get('start_date', '')
        end_date = trip_data.get('end_date', '')
        duration_days = 1
        
        if start_date and end_date:
            try:
                start = datetime.fromisoformat(start_date.replace('Z', '+00:00'))
                end = datetime.fromisoformat(end_date.replace('Z', '+00:00'))
                duration_days = (end - start).days + 1
            except:
                duration_days = len(trip_data.get('itineraries', []))
        
        # Prepare food preferences
        food_preferences = []
        if share_options.get('include_food_preferences'):
            mood = trip_data.get('mood', 'happy').lower()
            if mood == 'cultural':
                food_preferences = ["Local Cuisine", "Traditional Food", "Street Food", "Regional Specialties"]
            elif mood == 'adventurous':
                food_preferences = ["Street Food", "Local Markets", "Food Trucks", "Authentic Dishes"]
            elif mood == 'romantic':
                food_preferences = ["Fine Dining", "Wine Tasting", "Romantic Restaurants", "Local Delicacies"]
            else:
                food_preferences = ["Local Specialties", "Popular Restaurants", "Recommended Dishes"]
        
        # Enhanced shared data
        shared_data = {
            "share_id": share_id,
            "destination": trip_data['destination'],
            "start_date": start_date[:10] if start_date else "TBD",
            "end_date": end_date[:10] if end_date else "TBD",
            "duration_days": duration_days,
            "message": share_options.get('message', ''),
            "mood": trip_data.get('mood', 'adventure').title(),
            "activities_count": sum(
                len(day.get('activities', [])) for day in trip_data.get('itineraries', [])
            ),
            "shared_by": f"User {user_id}",
            "created_at": datetime.now().isoformat(),
            "expires_at": (datetime.now() + timedelta(days=7)).timestamp(),
            "itineraries": trip_data.get('itineraries', [])
        }
        
        # Add optional information
        if share_options.get('include_food_preferences'):
            shared_data['food_preferences'] = food_preferences
        
        if share_options.get('include_eco_info'):
            shared_data['eco_mode_enabled'] = trip_data.get('eco_mode_enabled', False)
            shared_data['transport_preference'] = trip_data.get('transport_preference', 'Mixed')
            shared_data['eco_score'] = 85 if trip_data.get('eco_mode_enabled') else 65
            shared_data['carbon_footprint_saved'] = round(duration_days * 2.5, 1) if trip_data.get('eco_mode_enabled') else 0
        
        # Store shared data
        self.shared_itineraries[share_id] = shared_data
        
        return {
            "share_id": share_id,
            "share_url": f"http://localhost:8000/api/export/shared/{share_id}",
            "expires_at": shared_data['expires_at'],
            "preview": {
                "destination": shared_data['destination'],
                "duration": f"{duration_days} days",
                "activities": shared_data['activities_count'],
                "eco_mode": shared_data.get('eco_mode_enabled', False)
            }
        }

