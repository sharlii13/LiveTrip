@router.get("/download/{trip_id}",
            summary="Download Itinerary",
            description="Download itinerary in various formats (TXT, JSON)")
async def download_itinerary(
    trip_id: int,
    format: str = Query("txt", pattern="^(txt|json)$", description="Download format"),
    db: Session = Depends(get_db)
):
    """📥 Download itinerary in various formats"""
    
    try:
        # Get trip data (use mock data if database unavailable)
        if db is None or trip_id in MOCK_TRIPS:
            trip_data = MOCK_TRIPS.get(trip_id)
            if not trip_data:
                raise HTTPException(status_code=404, detail="Trip not found")
        else:
            # Database query logic would go here
            trip_data = MOCK_TRIPS.get(1)  # Fallback to mock
        
        # Add food preferences based on mood
        mood = trip_data.get('mood', 'happy').lower()
        if mood == 'cultural':
            trip_data['food_preferences'] = ["Local Cuisine", "Street Food", "Traditional Dishes"]
        elif mood == 'adventurous':
            trip_data['food_preferences'] = ["Street Food", "Local Markets", "Food Trucks"]
        else:
            trip_data['food_preferences'] = ["Popular Restaurants", "Local Specialties"]
        
        # Generate download based on format
        if format.lower() == "txt":
            text_data = export_service._generate_text_itinerary(trip_data)
            
            return StreamingResponse(
                io.StringIO(text_data),
                media_type="text/plain",
                headers={
                    "Content-Disposition": f"attachment; filename=itinerary_{trip_data['destination'].replace(' ', '_')}_{trip_id}.txt"
                }
            )
            
        elif format.lower() == "json":
            json_data = await export_service.generate_json_export(trip_data)
            
            return StreamingResponse(
                io.StringIO(json.dumps(json_data, indent=2)),
                media_type="application/json",
                headers={
                    "Content-Disposition": f"attachment; filename=itinerary_{trip_data['destination'].replace(' ', '_')}_{trip_id}.json"
                }
            )
        
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Download failed: {e}")
        raise HTTPException(status_code=500, detail=f"Download failed: {str(e)}")

